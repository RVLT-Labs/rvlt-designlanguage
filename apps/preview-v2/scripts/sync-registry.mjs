#!/usr/bin/env node
// Copies the @rvlt/flow-theme registry source (packages/flow-theme/registry/rvlt) into
// src/registry/, and the documented examples (packages/flow-theme/examples) into src/examples/,
// before every dev, typecheck and build, so preview-v2 renders and type-checks the distributed
// components and the docs examples themselves. Both folders are generated and git-ignored.
import { cpSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FROM = path.resolve(APP, "../../packages/flow-theme/registry/rvlt");
const TO = path.join(APP, "src/registry");
const EX_FROM = path.resolve(APP, "../../packages/flow-theme/examples");
const EX_TO = path.join(APP, "src/examples");
for (const [from, to] of [[FROM, TO], [EX_FROM, EX_TO]]) {
  rmSync(to, { recursive: true, force: true });
  cpSync(from, to, { recursive: true });
  writeFileSync(path.join(to, "README.md"), `GENERATED by scripts/sync-registry.mjs from ${path.relative(path.resolve(APP, "../.."), from)}. Do not edit here.\n`);
  console.log(`${path.relative(path.resolve(APP, "../.."), from)} → ${path.relative(APP, to)}`);
}

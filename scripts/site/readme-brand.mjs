#!/usr/bin/env node
// Regenerates the colour palettes the root README shows (docs/brand/palette-{dark,light}.svg) from
// packages/flow-theme/tokens.json, so the README can never drift from the canonical tokens. GitHub
// renders README images without page CSS, so the swatches are drawn as SVG.
//
//   node scripts/site/readme-brand.mjs           # rewrite the palettes
//   node scripts/site/readme-brand.mjs --check   # exit 1 if they are stale
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(REPO, "docs/brand");
const tokens = JSON.parse(readFileSync(path.join(REPO, "packages/flow-theme/tokens.json"), "utf8"));
const CHECK = process.argv.includes("--check");

// The rows the README shows: the roles a reader needs, not every token.
const ROWS = [
  ["Surfaces", ["paper", "paper-2", "card", "elev"]],
  ["Text", ["ink", "ink-2", "muted"]],
  ["Red", ["red", "action-red", "red-text"]],
  ["Status", ["ok", "warn", "t-out", "rep", "info"]],
  ["Module hues", ["blue", "amber", "green", "purple", "coral", "teal"]],
];
const SW = { w: 112, h: 56, gap: 16, label: 128, pad: 32, row: 112 };
const MONO = "'Geist Mono', ui-monospace, SFMono-Regular, Menlo, Consolas, monospace";
const SANS = "'Hanken Grotesk', system-ui, -apple-system, 'Segoe UI', sans-serif";

function palette(theme) {
  const t = tokens.themes[theme];
  // sh-card's colour, e.g. "0 3px 0 #0C0A08" or "0 3px 0 var(--line-2)".
  const shadow = t["sh-card"].split(" ").pop().replace(/^var\(--([a-z0-9-]+)\)$/, (_, n) => t[n]);
  const cols = Math.max(...ROWS.map(([, names]) => names.length));
  const width = SW.pad * 2 + SW.label + cols * SW.w + (cols - 1) * SW.gap;
  const height = SW.pad * 2 + (ROWS.length - 1) * SW.row + SW.h + 40;
  const out = [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-label="RVLT ${theme === "dark" ? "Espresso" : "Paper"} palette">`,
    `<!-- Generated by scripts/site/readme-brand.mjs from packages/flow-theme/tokens.json. Do not edit. -->`,
    `<rect width="${width}" height="${height}" rx="20" fill="${t.paper}" stroke="${t["line-2"]}" stroke-width="2"/>`,
  ];
  ROWS.forEach(([label, names], r) => {
    const y = SW.pad + r * SW.row;
    out.push(`<text x="${SW.pad}" y="${y + SW.h / 2 + 5}" font-family="${SANS}" font-size="14" font-weight="700" fill="${t["ink-2"]}">${label}</text>`);
    names.forEach((name, c) => {
      const x = SW.pad + SW.label + c * (SW.w + SW.gap);
      const value = t[name];
      if (!/^#[0-9a-f]{6}$/i.test(value)) throw new Error(`${theme}.${name} is not a hex colour: ${value}`);
      // The brand's physical edge: a 2px outline and a hard offset shadow, never a blur.
      out.push(`<rect x="${x}" y="${y + 3}" width="${SW.w}" height="${SW.h}" rx="10" fill="${shadow}"/>`);
      out.push(`<rect x="${x}" y="${y}" width="${SW.w}" height="${SW.h}" rx="10" fill="${value}" stroke="${t["line-2"]}" stroke-width="2"/>`);
      out.push(`<text x="${x}" y="${y + SW.h + 20}" font-family="${MONO}" font-size="12" font-weight="600" fill="${t.ink}">${name}</text>`);
      out.push(`<text x="${x}" y="${y + SW.h + 36}" font-family="${MONO}" font-size="11" fill="${t.muted}">${value.toUpperCase()}</text>`);
    });
  });
  out.push("</svg>");
  return out.join("\n") + "\n";
}

let stale = 0;
mkdirSync(OUT, { recursive: true });
for (const theme of ["dark", "light"]) {
  const file = path.join(OUT, `palette-${theme}.svg`);
  const svg = palette(theme);
  if (CHECK) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== svg) {
      console.error(`${path.relative(REPO, file)} is stale: run node scripts/site/readme-brand.mjs`);
      stale++;
    }
  } else writeFileSync(file, svg);
}
if (stale) process.exit(1);
console.log(CHECK ? "README palettes match tokens.json" : `README palettes written to ${path.relative(REPO, OUT)}/`);
